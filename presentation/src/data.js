// День 1 (понедельник в демо-расписании) — будний день с полной загрузкой.
const DAY = 1;
const LOAD = [.55,.72,.78,.74,.66,.45,.28,.14];

export function slotState(roomId, slot){
  const key = roomId + "|" + slot + "|" + DAY, r = h(key);
  if (r < LOAD[slot]) return { st:"busy", title: CLASSES[Math.floor(h(key + "c") * CLASSES.length)] };
  return { st:"free" };
}

export function roomStatus(r, slot){
  if (r.srv) return "srv";
  const cur = slotState(r.id, slot).st;
  const nxt = slot + 1 < SLOTS.length ? slotState(r.id, slot + 1).st : "free";
  if (cur === "busy") return "busy";
  if (nxt === "busy") return "soon";
  return "free";
}

export const STATS = (() => {
  const rooms = FLOORS.reduce((a, f) => a + f.list.length, 0);
  const book = FLOORS.reduce((a, f) => a + f.book.length, 0);
  const kinds = new Set(FLOORS.flatMap(f => f.book.map(r => r.kind))).size;
  return { floors: FLOORS.length, rooms, book, kinds, slots: book * SLOTS.length };
})();
